"""Generate AprilGrid 6x6 calibration target.

Creates a high-resolution PDF for printing and a Kalibr-compatible
target YAML configuration.

Specifications:
    Grid:           6x6 AprilTags
    Tag family:     36h11
    Tag size:       80 mm
    Tag spacing:    0.3 (relative to tag size = 24 mm)
    Board size:     600 mm x 600 mm

Output:
    calibration/aprilgrid.pdf        - Print at 100% scale
    calibration/april_6x6.yaml       - Kalibr target config

Usage:
    python calibration/generate_aprilgrid.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import cv2
import numpy as np
from matplotlib import pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages

GRID_ROWS = 6
GRID_COLS = 6
TAG_SIZE_MM = 80
TAG_SPACING_RATIO = 0.3
TAG_FAMILY = cv2.aruco.DICT_APRILTAG_36H11
DPI = 600


def generate_board():
    dictionary = cv2.aruco.getPredefinedDictionary(TAG_FAMILY)
    board = cv2.aruco.GridBoard(
        size=(GRID_COLS, GRID_ROWS),
        markerLength=TAG_SIZE_MM,
        markerSeparation=TAG_SIZE_MM * TAG_SPACING_RATIO,
        dictionary=dictionary,
    )
    return board, dictionary


def render_pdf(board, output_path: Path):
    spacing_mm = TAG_SIZE_MM * TAG_SPACING_RATIO
    board_width_mm = GRID_COLS * TAG_SIZE_MM + (GRID_COLS - 1) * spacing_mm
    board_height_mm = GRID_ROWS * TAG_SIZE_MM + (GRID_ROWS - 1) * spacing_mm

    margin_mm = 20
    total_width_mm = board_width_mm + 2 * margin_mm
    total_height_mm = board_height_mm + 2 * margin_mm

    pixels_per_mm = DPI / 25.4
    img_w = int(total_width_mm * pixels_per_mm)
    img_h = int(total_height_mm * pixels_per_mm)

    marker_length_px = int(TAG_SIZE_MM * pixels_per_mm)
    marker_spacing_px = int(spacing_mm * pixels_per_mm)

    dictionary = cv2.aruco.getPredefinedDictionary(TAG_FAMILY)
    board_obj = cv2.aruco.GridBoard(
        size=(GRID_COLS, GRID_ROWS),
        markerLength=marker_length_px,
        markerSeparation=marker_spacing_px,
        dictionary=dictionary,
    )

    img = board_obj.generateImage((img_w, img_h), borderBits=1)

    fig, ax = plt.subplots(1, 1, figsize=(total_width_mm / 25.4, total_height_mm / 25.4))
    ax.imshow(img, cmap='gray', vmin=0, vmax=255)
    ax.set_axis_off()
    fig.subplots_adjust(left=0, right=1, top=1, bottom=0)

    with PdfPages(str(output_path)) as pdf:
        pdf.savefig(fig, dpi=DPI)

    plt.close(fig)

    print(f"PDF saved: {output_path}")
    print(f"  Board size: {board_width_mm:.0f} x {board_height_mm:.0f} mm")
    print(f"  Tag size: {TAG_SIZE_MM} mm")
    print(f"  Spacing: {spacing_mm:.0f} mm")
    print(f"  Tags: {GRID_COLS}x{GRID_ROWS} = {GRID_COLS * GRID_ROWS}")


def generate_kalibr_yaml(output_path: Path):
    spacing = TAG_SIZE_MM * TAG_SPACING_RATIO
    board_width = GRID_COLS * TAG_SIZE_MM + (GRID_COLS - 1) * spacing
    board_height = GRID_ROWS * TAG_SIZE_MM + (GRID_ROWS - 1) * spacing

    target_yaml = f"""# AprilGrid 6x6 calibration target
# Generated by generate_aprilgrid.py
targetType: apriltag
targetRows: {GRID_ROWS}
targetCols: {GRID_COLS}
tagSize: {TAG_SIZE_MM / 1000:.4f}
spacingRatio: {TAG_SPACING_RATIO}
tagFamily: 36h11
# Board dimensions: {board_width:.0f} x {board_height:.0f} mm
# Print at 100% scale on rigid flat surface
"""
    output_path.write_text(target_yaml)
    print(f"Kalibr target YAML saved: {output_path}")


def generate_preview(board, output_path: Path):
    img = board.generateImage((1200, 1200), borderBits=1)
    cv2.imwrite(str(output_path), img)
    print(f"Preview saved: {output_path}")


if __name__ == "__main__":
    calib_dir = Path(__file__).resolve().parent

    board, dictionary = generate_board()

    render_pdf(board, calib_dir / "aprilgrid.pdf")
    generate_kalibr_yaml(calib_dir / "april_6x6.yaml")
    generate_preview(board, calib_dir / "aprilgrid_preview.png")
